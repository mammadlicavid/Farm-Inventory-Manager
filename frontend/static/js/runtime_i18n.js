  const activeExact = exact[lang] || {};
  const activePatterns = patterns[lang] || [];
  const exactEntries = Object.entries(activeExact);
  const normalizedExact = new Map(
    exactEntries.map(([source, target]) => [normalizeLookupValue(source), target]),
  );
  const sortedExactEntries = exactEntries
    .filter(([source]) => source && source.length >= 3)
    .sort((left, right) => right[0].length - left[0].length);
  const inlineReplaceEntries = sortedExactEntries.map(([source, target]) => ({
    regex: buildInlineReplaceRegex(source),
    target,
  }));
  const valueCache = new Map();
  const inlineValueCache = new Map();

  function normalizeLookupValue(value) {
    return String(value || "")
      .trim()
      .replace(/\u2026/g, "...")
      .replace(/\s+/g, " ")
      .toLocaleLowerCase("az");
  }

  function escapeRegex(value) {
    return String(value || "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  function buildInlineReplaceRegex(source) {
    const escaped = escapeRegex(source);
    if (/^[\p{L}\p{N}\s]+$/u.test(source)) {
      return new RegExp(`(^|[^\\p{L}\\p{N}])(${escaped})(?=$|[^\\p{L}\\p{N}])`, "giu");
    }
    return new RegExp(escaped, "giu");
  }

  function translateWithDjangoCatalog(value) {
    if (!value || typeof window.gettext !== "function") return value;
    try {
      const translated = window.gettext(value);
      return translated || value;
    } catch (error) {
      return value;
    }
  }

  function translateValue(value) {
    if (!value) return value;
    if (valueCache.has(value)) return valueCache.get(value);
    let translated = value;
    if (activeExact[value]) {
      translated = activeExact[value];
      valueCache.set(value, translated);
      return translated;
    }
    const normalizedValue = normalizeLookupValue(value);
    if (normalizedExact.has(normalizedValue)) {
      translated = normalizedExact.get(normalizedValue);
      valueCache.set(value, translated);
      return translated;
    }
    const catalogTranslated = translateWithDjangoCatalog(value);
    if (catalogTranslated && catalogTranslated !== value) {
      valueCache.set(value, catalogTranslated);
      return catalogTranslated;
    }
    for (const [pattern, replacement] of activePatterns) {
      if (pattern.test(value)) {
        translated = value.replace(pattern, replacement);
        valueCache.set(value, translated);
        return translated;
      }
    }
    valueCache.set(value, translated);
    return translated;
  }

  function shouldAttemptInlineTranslation(value) {
    if (!value) return false;
    return /[\d:(),/%+|/-]/.test(value) || value.includes("•") || value.includes("—");
  }

  function translateInlineValue(value) {
    if (!value) return value;
    if (inlineValueCache.has(value)) return inlineValueCache.get(value);
    const direct = translateValue(value);
    const normalizedValue = normalizeLookupValue(value);
    const hasExactMatch = normalizedExact.has(normalizedValue);
    if (hasExactMatch || direct !== value || !shouldAttemptInlineTranslation(value)) {
      inlineValueCache.set(value, direct);
      return direct;
    }

    let result = value;

    inlineReplaceEntries.forEach(({ regex, target }) => {
      result = result.replace(regex, (match, prefix, token) => {
        if (typeof token === "string") return `${prefix || ""}${target}`;
        return target;
      });
    });

    for (const [pattern, replacement] of activePatterns) {
      if (pattern.test(result)) result = result.replace(pattern, replacement);
    }

    inlineValueCache.set(value, result);
    return result;
  }

  function replacePreservingWhitespace(source, translated) {
    const leading = source.match(/^\s*/)?.[0] || "";
    const trailing = source.match(/\s*$/)?.[0] || "";
    return `${leading}${translated}${trailing}`;
  }

  function translateTextNode(node) {
    const original = node.nodeValue;
    const trimmed = original.trim();
    if (!trimmed) return;
    const translated = translateInlineValue(trimmed);
    if (translated !== trimmed) node.nodeValue = replacePreservingWhitespace(original, translated);
  }

  function translateAttributes(element) {
    ["placeholder", "title", "aria-label"].forEach((attr) => {
      const value = element.getAttribute(attr);
      if (!value) return;
      const translated = translateInlineValue(value);
      if (translated !== value) element.setAttribute(attr, translated);
    });
    if (element.tagName === "INPUT" && /^(submit|button)$/i.test(element.type || "")) {
      const value = element.getAttribute("value");
      if (!value) return;
      const translated = translateInlineValue(value);
      if (translated !== value) element.setAttribute("value", translated);
    }
  }

  function translateOptionElement(option) {
    if (!option) return;
    const value = option.textContent.trim();
    const translated = translateInlineValue(value);
    if (translated && translated !== value) option.textContent = translated;
  }

  const ATTRIBUTE_TRANSLATION_SELECTOR = "[placeholder],[title],[aria-label],input[type='submit'],input[type='button'],option";

  function translateTree(root) {
    if (!root) return;
    if (root.nodeType === Node.ELEMENT_NODE) {
      translateAttributes(root);
      if (root.tagName === "OPTION") {
        translateOptionElement(root);
        return;
      }
    }
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.parentElement) return NodeFilter.FILTER_REJECT;
        const tag = node.parentElement.tagName;
        if (["SCRIPT", "STYLE", "TEXTAREA", "OPTION"].includes(tag)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    textNodes.forEach(translateTextNode);
    root.querySelectorAll?.(ATTRIBUTE_TRANSLATION_SELECTOR).forEach((element) => {
      translateAttributes(element);
      if (element.tagName === "OPTION") translateOptionElement(element);
    });
  }

  function boot() {
    document.title = translateValue(document.title);
    translateTree(document.body);
  }

  let observerStarted = false;

  function startObserver() {
    if (observerStarted || !document.body) return;
    observerStarted = true;
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "title", "aria-label", "value"],
    });
  }

  function initializeRuntimeI18n() {
    if (!document.body) return;
    boot();
    startObserver();
    if (window.__releaseI18nPending) {
      window.__releaseI18nPending();
    } else {
      document.documentElement.removeAttribute("data-i18n-pending");
    }
  }

  window.runtimeI18n = {
    translateValue,
    translateInlineValue,
    translateTree,
  };

  if (document.body) {
    initializeRuntimeI18n();
  } else {
    document.addEventListener("DOMContentLoaded", initializeRuntimeI18n, { once: true });
  }

  const pendingElements = new Set();
  const pendingTextNodes = new Set();
  let observerScheduled = false;

  function flushPendingTranslations() {
    observerScheduled = false;
    pendingTextNodes.forEach((node) => translateTextNode(node));
    pendingElements.forEach((node) => translateTree(node));
    pendingTextNodes.clear();
    pendingElements.clear();
  }

  function scheduleTranslationFlush() {
    if (observerScheduled) return;
    observerScheduled = true;
    window.requestAnimationFrame(flushPendingTranslations);
  }

  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === "characterData" && mutation.target?.nodeType === Node.TEXT_NODE) {
        pendingTextNodes.add(mutation.target);
      }
      if (mutation.type === "attributes" && mutation.target?.nodeType === Node.ELEMENT_NODE) {
        pendingElements.add(mutation.target);
      }
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) {
          pendingTextNodes.add(node);
          return;
        }
        if (node.nodeType === Node.ELEMENT_NODE) pendingElements.add(node);
      });
    });
    scheduleTranslationFlush();
  });

